CREATE OR REPLACE FUNCTION public.enforce_campaign_scope_integrity_v1()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  IF TG_TABLE_NAME = 'lead_import_batches' THEN
    IF NEW.audience_id IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.audiences a
      WHERE a.id = NEW.audience_id
        AND a.persona_id = NEW.persona_id
        AND COALESCE(a.metadata->>'kind', 'semantic_group') = 'semantic_group'
    ) THEN
      RAISE EXCEPTION 'import audience must be a semantic group in the same persona'
        USING ERRCODE = '23514';
    END IF;
  ELSIF TG_TABLE_NAME = 'lead_import_rows' THEN
    IF NOT EXISTS (
      SELECT 1 FROM public.lead_import_batches b
      WHERE b.id = NEW.batch_id AND b.persona_id = NEW.persona_id
    ) OR (
      NEW.lead_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.leads l
        WHERE l.id = NEW.lead_id AND l.persona_id = NEW.persona_id
      )
    ) THEN
      RAISE EXCEPTION 'import row scope mismatch' USING ERRCODE = '23514';
    END IF;
  ELSIF TG_TABLE_NAME = 'contact_consents' THEN
    IF NOT EXISTS (
      SELECT 1 FROM public.leads l
      WHERE l.id = NEW.lead_id AND l.persona_id = NEW.persona_id
    ) OR (
      NEW.campaign_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.campaigns c
        WHERE c.id = NEW.campaign_id AND c.persona_id = NEW.persona_id
      )
    ) OR (
      NEW.import_batch_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.lead_import_batches b
        WHERE b.id = NEW.import_batch_id AND b.persona_id = NEW.persona_id
      )
    ) THEN
      RAISE EXCEPTION 'consent scope mismatch' USING ERRCODE = '23514';
    END IF;
  ELSIF TG_TABLE_NAME = 'campaign_revisions' THEN
    IF NOT EXISTS (
      SELECT 1 FROM public.campaigns c
      WHERE c.id = NEW.campaign_id AND c.persona_id = NEW.persona_id
    ) OR NOT EXISTS (
      SELECT 1 FROM public.audiences a
      WHERE a.id = NEW.audience_id AND a.persona_id = NEW.persona_id
        AND COALESCE(a.metadata->>'kind', 'semantic_group') = 'semantic_group'
    ) THEN
      RAISE EXCEPTION 'campaign revision scope mismatch' USING ERRCODE = '23514';
    END IF;
  ELSIF TG_TABLE_NAME = 'campaign_revision_imports' THEN
    IF NOT EXISTS (
      SELECT 1
      FROM public.campaign_revisions r
      JOIN public.lead_import_batches b ON b.id = NEW.import_batch_id
      WHERE r.id = NEW.campaign_revision_id AND r.persona_id = b.persona_id
    ) THEN
      RAISE EXCEPTION 'campaign import scope mismatch' USING ERRCODE = '23514';
    END IF;
  ELSIF TG_TABLE_NAME = 'campaign_recipients' THEN
    IF NOT EXISTS (
      SELECT 1
      FROM public.campaigns c
      JOIN public.campaign_revisions r
        ON r.id = NEW.campaign_revision_id
       AND r.campaign_id = c.id
       AND r.revision = NEW.campaign_revision
      JOIN public.leads l ON l.id = NEW.lead_id
      WHERE c.id = NEW.campaign_id
        AND c.persona_id = NEW.persona_id
        AND r.persona_id = NEW.persona_id
        AND r.policy_checksum = NEW.policy_checksum
        AND l.persona_id = NEW.persona_id
        AND (
          NEW.applicable_consent_id IS NULL
          OR EXISTS (
            SELECT 1 FROM public.contact_consents cc
            WHERE cc.id = NEW.applicable_consent_id
              AND cc.lead_id = NEW.lead_id
              AND cc.persona_id = NEW.persona_id
          )
        )
    ) THEN
      RAISE EXCEPTION 'campaign recipient scope mismatch' USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

