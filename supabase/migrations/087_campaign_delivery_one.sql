-- Persistence is atomic without coupling the policy gate into one SQL function.
-- Eligibility remains split in the backend; this function only commits a
-- previously evaluated immutable revision and its recipient projection.
CREATE OR REPLACE FUNCTION public.create_campaign_draft_v1(
  p_campaign jsonb,
  p_revision jsonb,
  p_import_ids jsonb,
  p_recipients jsonb,
  p_event jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_campaign_id uuid := (p_campaign->>'id')::uuid;
  v_revision_id uuid := (p_revision->>'id')::uuid;
  v_existing_id uuid;
BEGIN
  SELECT id INTO v_existing_id
  FROM public.campaigns
  WHERE idempotency_key = p_campaign->>'idempotency_key';
  IF v_existing_id IS NOT NULL THEN
    RETURN jsonb_build_object('campaign_id', v_existing_id, 'deduplicated', true);
  END IF;

  INSERT INTO public.campaigns (
    id, persona_id, slug, name, status, format, metadata, created_at, updated_at,
    campaign_kind, purpose, channel, provider, audience_id, current_revision,
    idempotency_key, reason, created_by_user_id
  ) VALUES (
    v_campaign_id, (p_campaign->>'persona_id')::uuid, p_campaign->>'slug',
    p_campaign->>'name', p_campaign->>'status', p_campaign->>'format',
    COALESCE(p_campaign->'metadata', '{}'::jsonb),
    (p_campaign->>'created_at')::timestamptz,
    (p_campaign->>'updated_at')::timestamptz,
    p_campaign->>'campaign_kind', p_campaign->>'purpose', p_campaign->>'channel',
    p_campaign->>'provider', (p_campaign->>'audience_id')::uuid,
    (p_campaign->>'current_revision')::integer, p_campaign->>'idempotency_key',
    p_campaign->>'reason', NULLIF(p_campaign->>'created_by_user_id', '')::uuid
  );

  INSERT INTO public.campaign_revisions (
    id, campaign_id, persona_id, revision, audience_id, campaign_kind, purpose,
    objective, channel, provider, graph_version, graph_checksum,
    audience_snapshot, content_snapshot, policy_snapshot, policy_checksum,
    revision_checksum, status,
    created_by_user_id, reason, created_at
  ) VALUES (
    v_revision_id, v_campaign_id, (p_revision->>'persona_id')::uuid,
    (p_revision->>'revision')::integer, (p_revision->>'audience_id')::uuid,
    p_revision->>'campaign_kind', p_revision->>'purpose', p_revision->>'objective',
    p_revision->>'channel', p_revision->>'provider',
    NULLIF(p_revision->>'graph_version', '')::integer, p_revision->>'graph_checksum',
    COALESCE(p_revision->'audience_snapshot', '{}'::jsonb),
    COALESCE(p_revision->'content_snapshot', '{}'::jsonb),
    COALESCE(p_revision->'policy_snapshot', '{}'::jsonb),
    p_revision->>'policy_checksum', p_revision->>'revision_checksum',
    p_revision->>'status',
    NULLIF(p_revision->>'created_by_user_id', '')::uuid,
    p_revision->>'reason', (p_revision->>'created_at')::timestamptz
  );

  INSERT INTO public.campaign_revision_imports (campaign_revision_id, import_batch_id)
  SELECT v_revision_id, value::uuid
  FROM jsonb_array_elements_text(COALESCE(p_import_ids, '[]'::jsonb));

  INSERT INTO public.campaign_recipients (
    campaign_id, campaign_revision_id, campaign_revision, lead_id, persona_id,
    applicable_consent_id, consent_status, sequence_status, suppression_status,
    contact_status, blocked_reason, policy_checksum
  )
  SELECT
    v_campaign_id, v_revision_id, (p_revision->>'revision')::integer,
    (item->>'lead_id')::bigint,
    (p_campaign->>'persona_id')::uuid,
    NULLIF(item->>'applicable_consent_id', '')::uuid,
    item->>'consent_status', item->>'sequence_status',
    item->>'suppression_status', item->>'contact_status',
    item->>'blocked_reason', p_revision->>'policy_checksum'
  FROM jsonb_array_elements(COALESCE(p_recipients, '[]'::jsonb)) AS item;

  INSERT INTO public.system_events (
    event_type, entity_type, entity_id, persona_id, payload, level, source
  ) VALUES (
    'campaign_draft_created', 'campaign', v_campaign_id,
    (p_campaign->>'persona_id')::uuid, COALESCE(p_event, '{}'::jsonb),
    'info', 'campaigns.create'
  );

  RETURN jsonb_build_object('campaign_id', v_campaign_id, 'deduplicated', false);
END;
$$;

CREATE OR REPLACE FUNCTION public.transition_campaign_status_v1(
  p_campaign_id uuid,
  p_expected_revision integer,
  p_status text,
  p_idempotency_key text,
  p_reason text,
  p_actor_user_id uuid DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_campaign public.campaigns%ROWTYPE;
  v_event_type text;
BEGIN
  IF p_status NOT IN ('paused', 'cancelled') THEN
    RAISE EXCEPTION 'unsupported rollout-one campaign transition' USING ERRCODE = '22023';
  END IF;
  IF NULLIF(btrim(p_idempotency_key), '') IS NULL OR NULLIF(btrim(p_reason), '') IS NULL THEN
    RAISE EXCEPTION 'idempotency key and reason are required' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_campaign
  FROM public.campaigns
  WHERE id = p_campaign_id
  FOR UPDATE;
  IF v_campaign.id IS NULL THEN
    RAISE EXCEPTION 'campaign not found' USING ERRCODE = 'P0002';
  END IF;

  v_event_type := 'campaign_' || p_status;
  IF EXISTS (
    SELECT 1 FROM public.system_events
    WHERE event_type = v_event_type
      AND entity_id::text = p_campaign_id::text
      AND payload->>'idempotency_key' = p_idempotency_key
  ) THEN
    RETURN jsonb_build_object('campaign_id', p_campaign_id, 'deduplicated', true);
  END IF;

  IF v_campaign.current_revision <> p_expected_revision THEN
    RAISE EXCEPTION 'campaign revision conflict' USING ERRCODE = '40001';
  END IF;
  IF v_campaign.status IN ('completed', 'cancelled', 'failed', 'finished') THEN
    RAISE EXCEPTION 'terminal campaign cannot transition' USING ERRCODE = '55000';
  END IF;

  UPDATE public.campaigns
  SET status = p_status, updated_at = now()
  WHERE id = p_campaign_id;

  INSERT INTO public.system_events (
    event_type, entity_type, entity_id, persona_id, payload, level, source
  ) VALUES (
    v_event_type, 'campaign', p_campaign_id, v_campaign.persona_id,
    jsonb_build_object(
      'campaign_revision', p_expected_revision,
      'idempotency_key', p_idempotency_key,
      'reason', p_reason,
      'actor_user_id', p_actor_user_id
    ),
    'info', 'campaigns.status'
  );

  RETURN jsonb_build_object('campaign_id', p_campaign_id, 'deduplicated', false);
END;
$$;

CREATE OR REPLACE FUNCTION public.record_contact_consent_v1(
  p_consent jsonb,
  p_event jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_row public.contact_consents%ROWTYPE;
  v_status text := p_consent->>'status';
BEGIN
  IF v_status NOT IN ('pending', 'granted', 'refused', 'revoked', 'review_required') THEN
    RAISE EXCEPTION 'invalid consent status' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_row
  FROM public.contact_consents
  WHERE idempotency_key = p_consent->>'idempotency_key';
  IF v_row.id IS NOT NULL THEN
    RETURN to_jsonb(v_row) || jsonb_build_object('deduplicated', true);
  END IF;

  INSERT INTO public.contact_consents (
    lead_id, persona_id, channel, purpose, communication_category, status,
    source, request_message_id, response_message_id, campaign_id,
    import_batch_id, effective_at, granted_at, revoked_at, valid_until,
    evidence, actor_user_id, idempotency_key, created_at
  ) VALUES (
    (p_consent->>'lead_id')::bigint,
    (p_consent->>'persona_id')::uuid,
    lower(btrim(p_consent->>'channel')),
    btrim(p_consent->>'purpose'),
    NULLIF(btrim(p_consent->>'communication_category'), ''),
    v_status,
    btrim(p_consent->>'source'),
    NULLIF(p_consent->>'request_message_id', '')::bigint,
    NULLIF(p_consent->>'response_message_id', '')::bigint,
    NULLIF(p_consent->>'campaign_id', '')::uuid,
    NULLIF(p_consent->>'import_batch_id', '')::uuid,
    COALESCE(NULLIF(p_consent->>'effective_at', '')::timestamptz, now()),
    NULLIF(p_consent->>'granted_at', '')::timestamptz,
    NULLIF(p_consent->>'revoked_at', '')::timestamptz,
    NULLIF(p_consent->>'valid_until', '')::timestamptz,
    COALESCE(p_consent->'evidence', '{}'::jsonb),
    NULLIF(p_consent->>'actor_user_id', '')::uuid,
    p_consent->>'idempotency_key',
    COALESCE(NULLIF(p_consent->>'created_at', '')::timestamptz, now())
  ) RETURNING * INTO v_row;

  INSERT INTO public.system_events (
    event_type, entity_type, entity_id, persona_id, payload, level, source
  ) VALUES (
    'contact_consent_' || v_status,
    'lead', v_row.lead_id::text, v_row.persona_id,
    COALESCE(p_event, '{}'::jsonb) || jsonb_build_object('consent_id', v_row.id),
    'info', 'leads.consent'
  );

  RETURN to_jsonb(v_row) || jsonb_build_object('deduplicated', false);
END;
$$;

