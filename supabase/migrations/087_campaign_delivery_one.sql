    THEN (e.payload->>'row_index')::integer ELSE 1 END,
  CASE WHEN COALESCE(e.payload->>'lead_ref', '') ~ '^[0-9]+$'
    THEN (e.payload->>'lead_ref')::bigint ELSE NULL END,
