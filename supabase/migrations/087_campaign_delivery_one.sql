CREATE OR REPLACE FUNCTION public.enforce_single_semantic_group_v1()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  v_persona_id uuid;
  v_kind text;
BEGIN
  SELECT a.persona_id, COALESCE(a.metadata->>'kind', 'semantic_group')
  INTO v_persona_id, v_kind
  FROM public.audiences a
  WHERE a.id = NEW.audience_id;

  IF v_kind = 'semantic_group' AND EXISTS (
    SELECT 1
    FROM public.lead_audience_memberships lam
    JOIN public.audiences a ON a.id = lam.audience_id
    WHERE lam.lead_id = NEW.lead_id
      AND a.persona_id = v_persona_id
      AND COALESCE(a.metadata->>'kind', 'semantic_group') = 'semantic_group'
      AND lam.id IS DISTINCT FROM NEW.id
  ) THEN
    RAISE EXCEPTION 'lead already belongs to a semantic group in this persona'
