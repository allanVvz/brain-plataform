-- Durable projection and command receipts for the Chatwoot API inbox bridge.
-- The bridge is additive: the existing Meta webhook remains the only source
-- of WhatsApp ingress and the existing transport remains the only sender.

CREATE TABLE IF NOT EXISTS public.chatwoot_bridge_conversations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_binding_id uuid NOT NULL REFERENCES public.workflow_bindings(id) ON DELETE CASCADE,
  lead_ref bigint NOT NULL REFERENCES public.leads(id) ON DELETE CASCADE,
  account_id bigint NOT NULL,
  inbox_id bigint NOT NULL,
  contact_id bigint NOT NULL,
  contact_identifier text NOT NULL,
  conversation_id bigint,
  last_projected_message_id bigint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (channel_binding_id, lead_ref),
  UNIQUE (account_id, inbox_id, conversation_id)
);

CREATE TABLE IF NOT EXISTS public.chatwoot_bridge_operations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  source_kind text NOT NULL CHECK (source_kind IN ('brain_message', 'chatwoot_event')),
  source_id text NOT NULL,
  operation text NOT NULL CHECK (operation IN (
    'project_message', 'human_reply', 'pause_ai', 'resume_ai'
  )),
  channel_binding_id uuid NOT NULL REFERENCES public.workflow_bindings(id) ON DELETE CASCADE,
  lead_ref bigint NOT NULL REFERENCES public.leads(id) ON DELETE CASCADE,
  brain_message_id bigint REFERENCES public.messages(id) ON DELETE CASCADE,
  chatwoot_message_id bigint,
  chatwoot_conversation_id bigint,
  transport_buffer_id uuid REFERENCES public.lead_buffer(id) ON DELETE SET NULL,
  chatwoot_delivery_status text CHECK (chatwoot_delivery_status IN ('sent','delivered','read','failed')),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN (
    'pending', 'processing', 'retry', 'completed', 'ignored', 'dead_letter'
  )),
  attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  available_at timestamptz NOT NULL DEFAULT now(),
  locked_at timestamptz,
  locked_by text,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_kind, source_id),
  CHECK (
    (source_kind = 'brain_message' AND brain_message_id IS NOT NULL
      AND operation = 'project_message')
    OR
    (source_kind = 'chatwoot_event' AND brain_message_id IS NULL
      AND operation IN ('human_reply', 'pause_ai', 'resume_ai')
      AND (operation='pause_ai' OR chatwoot_message_id IS NOT NULL))
  )
);

CREATE INDEX IF NOT EXISTS idx_chatwoot_bridge_operations_claim
  ON public.chatwoot_bridge_operations(status, available_at, created_at);
CREATE INDEX IF NOT EXISTS idx_chatwoot_bridge_operations_lead
  ON public.chatwoot_bridge_operations(channel_binding_id, lead_ref, created_at);

ALTER TABLE public.chatwoot_bridge_conversations ENABLE ROW LEVEL SECURITY;
